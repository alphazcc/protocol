#define CRC16_POLY   UINT16_C(0xA001)
#define CRC16_ROUNDS UINT8_C(8)

uint16_t proto_crc16_modbus(const uint8_t *data, size_t size)
{
    uint16_t crc = CRC16_SEED;
    size_t i;

    assert(data != NULL || size == 0U);

    for (i = 0; i < size; i++)
    {
        uint8_t bit;

        crc = (uint16_t)(crc ^ (uint16_t)data[i]);
        for (bit = 0; bit < CRC16_ROUNDS; bit++)
        {
            uint8_t lsb = (uint8_t)(crc & UINT16_C(0x0001));

            crc = (uint16_t)(crc >> 1);
            if (lsb != UINT8_C(0))
            {
                crc = (uint16_t)(crc ^ CRC16_POLY);
            }
        }
    }
    return crc;
}

