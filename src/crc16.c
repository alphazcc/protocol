uint16_t proto_crc16_modbus(const uint8_t *data, size_t size)
{
    uint16_t crc = CRC16_SEED;
    size_t i;

    assert(data != NULL || size == 0U);

    for (i = 0; i < size; i++)
    {
        crc = (uint16_t)((crc >> 8) ^ crc16_table[
            (size_t)((crc ^ (uint16_t)data[i]) & UINT16_C(0x00FF))]);
    }
    return crc;
}

